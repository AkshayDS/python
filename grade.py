Marks = float(input("Enter you marks = " ))

if( Marks>=90):
    print("The grade is 'Excelent'")
elif(Marks>=80):
    print("The grade is 'A'")
elif(Marks>=70):
    print("The grade is 'B'")
elif(Marks>=60):
    print("The grade is 'C'")
elif(Marks>=50):
    print("The grade is 'D'")
else:
    print(" 'fail'")
